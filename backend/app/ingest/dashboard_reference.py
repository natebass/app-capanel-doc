def seed_dashboard_reference(session: Session) -> None:
    """Populate the Dashboard reference tables.  Safe to call repeatedly."""
    from app.ingest.reference_data import _upsert

    _upsert(
        session,
        DashboardIndicator,
        [
            {
                "code": code,
                "name": name,
                "short_name": short_name,
                "lower_is_better": lower_is_better,
                "unit": unit,
                "sort_order": sort_order,
                "is_informational": informational,
            }
            for (
                code,
                name,
                short_name,
                lower_is_better,
                unit,
                sort_order,
                informational,
            ) in _INDICATORS
        ],
    )
    _upsert(
        session,
        DashboardStudentGroup,
        [
            {
                "code": code,
                "name": name,
                "category": category,
                "sort_order": sort_order,
            }
            for code, name, category, sort_order in _STUDENT_GROUPS
        ],
    )
    _upsert(
        session,
        DashboardCutpoint,
        [
            {
                "indicator_code": indicator,
                "variant": variant,
                "kind": kind,
                "level": level,
                "lower_bound": lower,
                "upper_bound": upper,
                "label": label,
            }
            for indicator, variant, kind, level, lower, upper, label in _CUTPOINTS
        ],
    )
    _upsert(
        session,
        DashboardColorCell,
        [
            {
                "indicator_code": indicator,
                "variant": variant,
                "small_denominator": small,
                "status_level": status,
                "change_level": change,
                "color": color,
            }
            for indicator, variant, small, status, change, color in _COLOR_CELLS
        ],
    )
