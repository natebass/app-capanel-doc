"""Seed data for the California School Dashboard accountability layer.

Three things are transcribed here:

``_INDICATORS``
    The seven state indicators, and which direction each is judged in.
``_CUTPOINTS``
    The status and change bands from the state's five-by-five colored tables
    at https://www.cde.ca.gov/ta/ac/cm/fivebyfivecolortables.asp.  Bounds are
    inclusive; an open end is ``None``, which is how the tables read ("+45.0
    points or more", "-70.1 points or fewer").
``_COLOR_CELLS``
    Every status x change cell of every grid.  The full-denominator cells are
    on that same page; the small-denominator ones are not published as tables
    anywhere and were derived from the indicator files themselves, then
    checked against the page wherever the two overlap.

Two rules are carried in code rather than data, in
:mod:`app.service.dashboard_projection`:

* Entities with fewer than 150 students are judged on a reduced grid.  For
  chronic absenteeism, suspension and college/career the five change bands
  collapse to three -- "increased significantly" folds into "increased" and
  "declined significantly" into "declined" -- and the cut points are otherwise
  unchanged.  Graduation keeps five bands but uses its own colors.
* A row flagged ``dataerrorflag`` carries a state override rather than a grid
  result, and is never reproduced.

Together these reproduce every ``statuslevel``, ``changelevel`` and ``color``
in the 2024-25 files exactly; see ``tests/service/test_dashboard_projection``.

Variants keep a cut point tied to the table it came from: suspension is
published as six tables keyed by the file's ``type`` column (``ED``, ``HD``,
``UD`` for districts; ``ES``, ``MS``, ``HS`` for schools) and the academic
indicators as two, split by the ``hscutpoints`` flag.
"""

